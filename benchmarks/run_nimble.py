"""Run the 324-record holdout shipped in the Nimble repository (benchmarks/nimble/data/eval.jsonl).

Note on the measurement basis: these 324 records are Nimble's synthetic corpus, with labels
generated by rules plus a model check and **no human review**, and Nimble has not published a
score for Jev on this file. It therefore serves only as an internal reference for this
implementation and cannot be compared directly against the 13 human-annotated subsets in
PUBLIC_BENCHMARKS.md.

The NeoHorse-Jev-4B model card from TokenRhythm publishes Nimble 87.23, computed on the
**282 records selected from this same 324**. The default `--subset compat282` reproduces that
selection basis:
    ① state ≤ 384 tokens
    ② the encoded decision input (the serialized request body) ≤ 2048 tokens
    ③ candidate count ≤ 26
    ④ keep case groups intact: if a case group contains even one failing record, drop the whole
      group (case groups come from the `family` field)
`--subset full324` keeps the old "all 324" behavior.

Usage:
    python3 benchmarks/run_nimble.py                       # default compat282
    python3 benchmarks/run_nimble.py --subset full324      # old basis, all 324
    python3 benchmarks/run_nimble.py --logit-bias --concurrency 6
"""

from __future__ import annotations

import argparse
import ast
import asyncio
import dataclasses
import json
import pathlib
import sys
import time
from typing import Optional, Tuple

PROJECT_ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "src"))
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

from llm2decision.llm.client import ChatClient  # noqa: E402
from llm2decision.core.config import Config  # noqa: E402
from llm2decision.core.schema import SystemOneRequest  # noqa: E402
from llm2decision.llm.service import SystemOneService  # noqa: E402
from run_jevbench import summarize  # noqa: E402

DATA = pathlib.Path(__file__).resolve().parent / "nimble" / "data" / "eval.jsonl"
RESULT_DIR = pathlib.Path(__file__).resolve().parent / "results"

SUBSETS = ("compat282", "full324")

# The base tokenizer pinned by TokenRhythm / Nimble (model card 2026-09-24). Use it when it can be
# fetched locally by revision; otherwise fall back to any available Qwen tokenizer (the difference
# is noted in the report and output).
TOKENIZER_ID = "Qwen/Qwen3.5-9B"
TOKENIZER_REVISION = "c202236235762e1c871ad0ccb60c8ee5ba337b9a"

STATE_MAX_TOKENS = 384
INPUT_MAX_TOKENS = 2048
MAX_CANDIDATES = 26

_TOKENIZER = None
_TOKENIZER_LABEL = ""


def parse(value):
    if isinstance(value, (dict, list)):
        return value
    return ast.literal_eval(value)


def load_items():
    items = []
    for line in DATA.read_text(encoding="utf-8").splitlines():
        if line.strip():
            items.append(json.loads(line))
    return items


def get_tokenizer():
    """Prefer the pinned Qwen3.5-9B, fall back to Qwen/Qwen3-8B on failure; returns (tokenizer, label)."""
    global _TOKENIZER, _TOKENIZER_LABEL
    if _TOKENIZER is not None:
        return _TOKENIZER, _TOKENIZER_LABEL
    from transformers import AutoTokenizer

    try:
        _TOKENIZER = AutoTokenizer.from_pretrained(TOKENIZER_ID, revision=TOKENIZER_REVISION)
        _TOKENIZER_LABEL = f"{TOKENIZER_ID}@{TOKENIZER_REVISION[:8]} (matches the version pinned by Nimble)"
    except Exception as exc:  # Fall back when the pinned version cannot be downloaded or installed on this machine
        fallback = "Qwen/Qwen3-8B"
        _TOKENIZER = AutoTokenizer.from_pretrained(fallback)
        _TOKENIZER_LABEL = (
            f"{fallback} (fallback: the pinned {TOKENIZER_ID}@{TOKENIZER_REVISION[:8]} is unavailable: "
            f"{type(exc).__name__}; both are Qwen-family BPE, so token counts may differ slightly)"
        )
    return _TOKENIZER, _TOKENIZER_LABEL


def candidate_count(question: dict) -> int:
    """The candidate count for a question: criteria count for choice/score, two (yes/no) for noul."""
    if question["type"] == "noul":
        return 2
    criteria = question.get("criteria")
    if isinstance(criteria, dict):
        return len(criteria)
    if isinstance(criteria, list):
        return len(criteria)
    return 2


def measure(item: dict, tokenizer) -> dict:
    """Compute the three screening metrics per record: state token count, request-body token count, candidate count."""
    raw = parse(item["input"])
    state = raw.get("state")
    if not isinstance(state, str):
        state = json.dumps(state, ensure_ascii=False)
    payload, _, _ = to_payload(item)
    body = json.dumps(payload, ensure_ascii=False)
    return {
        "state_tokens": len(tokenizer(state, add_special_tokens=False)["input_ids"]),
        "input_tokens": len(tokenizer(body, add_special_tokens=False)["input_ids"]),
        "candidates": candidate_count(raw["questions"]["decision"]),
    }


def filter_compat(items: list) -> Tuple[list, dict]:
    """Filter by the TokenRhythm basis: apply ①②③ per record, then keep case groups (family) intact."""
    tokenizer, tokenizer_label = get_tokenizer()
    groups: dict = {}
    for item in items:
        groups.setdefault(item.get("family"), []).append(item)

    stats = {
        "total": len(items),
        "groups": len(groups),
        "over_state": 0,
        "over_input": 0,
        "over_candidates": 0,
        "bad_records": 0,
        "dropped_groups": 0,
        "dropped_records": 0,
        "fail_state_ids": [],
        "fail_input_ids": [],
        "fail_candidate_ids": [],
        "tokenizer": tokenizer_label,
    }
    bad_ids = set()
    for item in items:
        metrics = measure(item, tokenizer)
        if metrics["state_tokens"] > STATE_MAX_TOKENS:
            stats["over_state"] += 1
            stats["fail_state_ids"].append((item["id"], metrics["state_tokens"]))
        if metrics["input_tokens"] > INPUT_MAX_TOKENS:
            stats["over_input"] += 1
            stats["fail_input_ids"].append((item["id"], metrics["input_tokens"]))
        if metrics["candidates"] > MAX_CANDIDATES:
            stats["over_candidates"] += 1
            stats["fail_candidate_ids"].append((item["id"], metrics["candidates"]))
        if (metrics["state_tokens"] > STATE_MAX_TOKENS
                or metrics["input_tokens"] > INPUT_MAX_TOKENS
                or metrics["candidates"] > MAX_CANDIDATES):
            bad_ids.add(item["id"])
    stats["bad_records"] = len(bad_ids)

    kept = []
    for family, group in groups.items():
        if any(member["id"] in bad_ids for member in group):
            stats["dropped_groups"] += 1
            stats["dropped_records"] += len(group)
            continue
        kept.extend(group)
    stats["kept"] = len(kept)
    return kept, stats


def print_filter_stats(stats: dict) -> None:
    print(f"filter basis compat282 (tokenizer: {stats['tokenizer']})")
    print(f"  raw {stats['total']} records / {stats['groups']} case groups (family)")
    print(f"  ① state > {STATE_MAX_TOKENS} tokens: {stats['over_state']} dropped")
    print(f"  ② request body > {INPUT_MAX_TOKENS} tokens: {stats['over_input']} dropped")
    print(f"  ③ candidates > {MAX_CANDIDATES}: {stats['over_candidates']} dropped")
    print(f"  ①②③ records failing any check (total): {stats['bad_records']} in total")
    print(f"  ④ keep whole groups: dropped {stats['dropped_groups']} groups, {stats['dropped_records']} records")
    print(f"  → after filtering: {stats['kept']} records (target 282)")


def to_payload(item: dict) -> Tuple[dict, str, str]:
    """Returns (request body, gold, question_type)."""
    raw = parse(item["input"])
    question = dict(raw["questions"]["decision"])
    qtype = question["type"]
    instructions = question.get("instructions", "") or ""

    if qtype == "score":
        levels = question.get("criteria") or []
        labels = [str(index) for index in range(len(levels))]
        # Chinese rubric prefix and separator kept as-is: the v1 prompt locale is Chinese and
        # every published number was measured with this exact string.
        question = {
            "type": "score",
            "instructions": instructions + "\n档位定义：" + "；".join(str(text) for text in levels),
            "scale": labels,
            "values": [float(label) for label in labels],
        }
    elif qtype == "noul":
        question = {"type": "noul", "instructions": instructions}

    state = raw.get("state")
    if not isinstance(state, str):
        state = json.dumps(state, ensure_ascii=False)

    gold = parse(item["reference"])["target"]
    return {"state": state, "questions": {"q": question}}, str(gold), qtype


def predicted_label(qtype: str, decision) -> Optional[str]:
    if qtype == "noul":
        if decision.true_probability is None:
            return None
        return "yes" if decision.true_probability >= 0.5 else "no"
    return decision.label


def normalize_gold(qtype: str, gold: str) -> str:
    if qtype == "noul":
        return "yes" if gold.strip().lower() in {"yes", "true", "1"} else "no"
    return str(gold)


async def run_item(service, item, semaphore, route: str) -> dict:
    payload, gold, qtype = to_payload(item)
    # The service resolves the route from the request body; without "model" here it would fall
    # back to default_model, which is not in this single-route client map (KeyError).
    payload = {**payload, "model": route}
    async with semaphore:
        started = time.perf_counter()
        try:
            response = await service.decide(SystemOneRequest(**payload))
            decision = response.decisions["q"]
            predicted = predicted_label(qtype, decision)
            correct = predicted is not None and str(predicted).lower() == normalize_gold(qtype, gold).lower()
            record = {
                "predicted": predicted,
                "correct": correct,
                "coverage": decision.coverage,
                "reliable": decision.reliable,
                "generated_token": decision.generated_token,
                "error": None,
            }
        except Exception as exc:
            record = {
                "predicted": None,
                "correct": False,
                "coverage": None,
                "reliable": None,
                "generated_token": None,
                "error": f"{type(exc).__name__}: {exc}",
            }
    record.update(
        {
            "id": item["id"],
            "tier": item.get("source_family") or "unknown",
            "family": item.get("family"),
            "type": qtype,
            "expected": gold,
            "latency_ms": round((time.perf_counter() - started) * 1000, 1),
        }
    )
    return record


async def main() -> int:
    parser = argparse.ArgumentParser(description="Run Nimble's bundled holdout")
    parser.add_argument("--subset", choices=SUBSETS, default="compat282",
                        help="compat282 = filter to 282 records by the TokenRhythm basis (default); full324 = all 324")
    parser.add_argument("--limit", type=int, default=0)
    parser.add_argument("--concurrency", type=int, default=6)
    parser.add_argument("--logit-bias", action="store_true")
    parser.add_argument("--model", help="model route name; defaults to default_model")
    parser.add_argument("--tag", default="")
    args = parser.parse_args()

    config = Config.load()
    route = args.model or config.default_model
    settings = config.resolve(route)
    if args.logit_bias:
        settings = dataclasses.replace(settings, logit_bias_enabled=True)

    items = load_items()
    filter_stats = None
    if args.subset == "compat282":
        items, filter_stats = filter_compat(items)
        print_filter_stats(filter_stats)
    if args.limit:
        items = items[: args.limit]
    print(f"model {settings.model} | Nimble {args.subset} {len(items)} records | logit_bias={settings.logit_bias_enabled}")

    client = ChatClient(settings)
    service = SystemOneService({route: client}, config)
    semaphore = asyncio.Semaphore(args.concurrency)
    started = time.perf_counter()
    try:
        records = list(await asyncio.gather(*(run_item(service, item, semaphore, route) for item in items)))
    finally:
        await client.aclose()

    summary = summarize(records)
    summary["model"] = settings.model
    summary["subset"] = args.subset
    if args.subset == "compat282":
        summary["dataset"] = (
            f"nimble/data/eval.jsonl compat282 ({len(items)} records after filtering by the TokenRhythm basis, "
            "state≤384/body≤2048/candidates≤26/whole groups kept)"
        )
        summary["filter"] = filter_stats
    else:
        summary["dataset"] = "nimble/data/eval.jsonl (324 synthetic holdout records, no human review)"
    summary["logit_bias_enabled"] = settings.logit_bias_enabled
    summary["elapsed_s"] = round(time.perf_counter() - started, 1)

    RESULT_DIR.mkdir(exist_ok=True)
    stamp = time.strftime("%Y%m%d-%H%M%S")
    tag = f"-{args.tag}" if args.tag else ""
    detail_path = RESULT_DIR / f"nimble-{stamp}{tag}.jsonl"
    summary_path = RESULT_DIR / f"nimble-{stamp}{tag}.summary.json"
    with detail_path.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")
    summary_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")

    overall = summary["overall"]
    print(f"\nNimble holdout: {overall['correct']}/{overall['n']} = {overall['accuracy']:.2%}"
          f" ({overall['errors']} failures)")
    for qtype, block in summary["by_type"].items():
        if block["n"]:
            print(f"  {qtype:<8} {block['correct']:>3}/{block['n']:<3} = {block['accuracy']:.2%}")
    print(f"  p50={overall['latency_p50_ms']}ms | total {summary['elapsed_s']}s")
    print(f"\ndetails: {detail_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
